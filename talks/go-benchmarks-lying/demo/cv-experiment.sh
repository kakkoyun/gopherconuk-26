#!/usr/bin/env bash
# Layer 3a live demo: does container isolation collapse benchmark variance?
#
# Runs the same benchmark under three conditions and reports CV for each:
#   idle   — bare host, machine quiet
#   noisy  — bare host, every core saturated by background spinners
#   pinned — container pinned to one core (--cpuset-cpus), same background load
#
# Results land in results/ and are committed so the slides can quote real numbers.
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")"

BENCH="${BENCH:-BenchmarkMakeBuffer_Correct}"
COUNT="${COUNT:-20}"
BENCHTIME="${BENCHTIME:-1s}"
IMAGE="${IMAGE:-golang:1.26}"
OUT=results
mkdir -p "$OUT"

case "$(uname -s)" in
    Darwin) NCPU=$(sysctl -n hw.ncpu) ;;
    *) NCPU=$(nproc) ;;
esac

load_pids=()

start_load() {
    local n=$1
    for ((i = 0; i < n; i++)); do
        # Busy spinner: no I/O, no allocation, pure CPU contention.
        (while :; do :; done) &
        load_pids+=("$!")
    done
    echo "started $n background spinners"
}

stop_load() {
    [[ ${#load_pids[@]} -eq 0 ]] && return 0
    kill "${load_pids[@]}" 2>/dev/null || true
    wait "${load_pids[@]}" 2>/dev/null || true
    load_pids=()
    echo "background load stopped"
}
trap stop_load EXIT

run_host() {
    go test -bench="$BENCH" -benchmem -count="$COUNT" -benchtime="$BENCHTIME" .
}

run_container() {
    docker run --rm \
        --cpuset-cpus=0 --cpus=1 --memory=512m \
        -v "$PWD:/app" -w /app \
        -e GOCACHE=/tmp/gocache -e GOFLAGS=-mod=mod \
        "$IMAGE" \
        go test -bench="$BENCH" -benchmem -count="$COUNT" -benchtime="$BENCHTIME" .
}

echo "=== 1/3 idle host ==="
run_host | tee "$OUT/idle.txt"

echo "=== 2/3 noisy host (${NCPU} spinners) ==="
start_load "$NCPU"
run_host | tee "$OUT/noisy.txt"
stop_load

echo "=== 3/3 pinned container, noisy host (${NCPU} spinners) ==="
start_load "$NCPU"
run_container | tee "$OUT/pinned.txt"
stop_load

{
    echo "# CV comparison — $BENCH, count=$COUNT, benchtime=$BENCHTIME"
    echo "# host: $(uname -srm), ${NCPU} logical CPUs"
    echo "# container image: $IMAGE (--cpuset-cpus=0 --cpus=1 --memory=512m)"
    echo "# generated by cv-experiment.sh"
    for f in idle noisy pinned; do
        echo
        echo "## $f"
        awk -f cv.awk "$OUT/$f.txt"
    done
} | tee "$OUT/cv-summary.txt"
